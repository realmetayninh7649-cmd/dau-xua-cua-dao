import test from 'node:test';
import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {execFileSync} from 'node:child_process';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {webcrypto} from 'node:crypto';
import {handleWorkingEditor} from '../workers/gdd-d1-admin/src/working-editor.mjs';
if(!globalThis.crypto)globalThis.crypto=webcrypto;
const temp=mkdtempSync(join(tmpdir(),'gdd-editor-all-nine-'));
const dbPath=join(temp,'clone.sqlite');
const python=[
 'import sqlite3,sys',
 'from scripts.gdd_prepare_d1_editor import migrate,root',
 'p=sys.argv[1]',
 'conn=sqlite3.connect(p)',
 'conn.row_factory=sqlite3.Row',
 'conn.executescript((root/"workers/gdd-d1/migrations/0001_supabase_21_tables.sql").read_text())',
 'class Adapter:',
 ' def query(self,sql):',
 '  cur=conn.execute(sql)',
 '  if cur.description:return [dict(row) for row in cur.fetchall()]',
 '  return []',
 'migrate(Adapter())',
 'conn.commit()',
 'conn.close()'
].join('\n');
execFileSync('python3',['-c',python,dbPath],{stdio:'pipe'});
const database=new DatabaseSync(dbPath);
const db={prepare(sql){
 const statement=database.prepare(sql);
 return {bind(...args){return {
  first:async()=>statement.get(...args)||null,
  all:async()=>({results:statement.all(...args)}),
  run:async()=>statement.run(...args)
 }},all:async()=>({results:statement.all()})};
}};
const ROOT='https://admin.test/api/v1/admin/work/';
const kinds=['people','posts','media','videos','obituaries','documents',
 'gdd_memorials','gdd_audio_programs','gdd_calendar_memorials'];
async function call(method,relative,payload){
 const req=new Request(ROOT+relative,{method,headers:{'Content-Type':'application/json'},
  body:payload?JSON.stringify(payload):undefined});
 const response=await handleWorkingEditor(req,db,new URL(req.url).pathname);
 return {status:response.status,body:await response.json()};
}
test('real 21-table SQLite schema supports draft creation and listing of all nine kinds',async()=>{
 for(const kind of kinds){
  const name=kind==='people'||kind==='gdd_calendar_memorials'?'full_name':'title';
  const created=await call('POST',kind,{fields:{[name]:'Tư liệu kiểm thử riêng tư '+kind,published:false}});
  assert.equal(created.status,201,JSON.stringify({kind,error:created.body.error}));
  assert.equal(created.body.data.published,0);
  assert.equal(created.body.data.gdd_version,1);
  const id=created.body.data.id;
  const listing=await call('GET',kind+'?limit=50');
  assert.equal(listing.status,200,JSON.stringify({kind,error:listing.body.error}));
  assert.ok(listing.body.data.some(r=>r.id===id),'new draft missing '+kind);
  const field=kind==='gdd_calendar_memorials'?'description':
    kind==='media'?'caption':'summary';
  const edited=await call('PATCH',kind+'/'+id,{
   version:1,fields:{[field]:'Biên tập mẫu '+kind}});
  assert.equal(edited.status,200,JSON.stringify({kind,error:edited.body.error}));
  assert.equal(edited.body.data.gdd_version,2);
  assert.equal(edited.body.data[field],'Biên tập mẫu '+kind);
  const history=await call('GET',kind+'/'+id+'/history');
  assert.equal(history.status,200);
  assert.equal(history.body.data.length,2,'missing create/update audit trigger: '+kind);
  assert.equal((await call('PATCH',kind+'/'+id,{version:1,fields:{[field]:'conflict'}})).status,409);
 }
 console.log('NINE_KIND_D1_LOCAL_SQLITE_CREATE_LIST_UPDATE_AUDIT=PASS');
});
test('no archive IDs are changed or generated by draft editor',async()=>{
 const rows=database.prepare('SELECT archive_code FROM people').all();
 assert.ok(rows.every(x=>x.archive_code===null));
});
test('no real external D1, R2 or Supabase requests are performed',()=>{
 assert.ok(database.prepare('SELECT COUNT(*) AS n FROM gdd_v2_editor_revisions').get().n>=18);
});
process.on('exit',()=>{try{database.close()}catch{}try{rmSync(temp,{recursive:true,force:true})}catch{}});
